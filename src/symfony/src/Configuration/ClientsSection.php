<?php

declare(strict_types=1);

namespace Beffroi\Bundle\Configuration;

use Beffroi\Oidc\Bridge\Configuration\ConfigurationClientRepository;
use Beffroi\Oidc\Domain\Client\Metadata\DeploymentDefaults;
use Beffroi\Oidc\Domain\Client\Certificate\CertificateIdentities;
use function is_array;
use Symfony\Component\Config\Definition\Builder\NodeBuilder;
use Symfony\Component\DependencyInjection\Loader\Configurator\ServicesConfigurator;

/**
 * The clients of the tenant, as a deployment declares them (architecture §5.1). They belong to the tenant this deployment declares, which is why the repository is told its slug.
 */
final readonly class ClientsSection extends ConfigurationSection
{
    public function name(): string
    {
        return 'clients';
    }

    public function describe(NodeBuilder $children): void
    {
        $children
            ->arrayNode('clients')
            ->info('The clients of the tenant, keyed by client identifier. A secret is hashed when the client is loaded and never kept in clear, unless the method it registered has to compute a MAC with it (client_secret_jwt).')
            ->useAttributeAsKey('client_id')
            ->normalizeKeys(false)
            ->arrayPrototype()
            ->children()
            ->scalarNode('client_name')
            ->info('Shown on the consent page (OIDC Registration §2); the client identifier when absent.')
            ->defaultNull()
            ->end()
            ->scalarNode('client_uri')
            ->info('The home page of the client (OIDC Registration §2), linked from the consent page; HTTPS, or plain HTTP on a loopback host.')
            ->defaultNull()
            ->end()
            ->scalarNode('logo_uri')
            ->info('The logo the consent page shows for this client (OIDC Registration §2); HTTPS, or plain HTTP on a loopback host.')
            ->defaultNull()
            ->end()
            ->scalarNode('policy_uri')
            ->info('How this client uses the data it is given (OIDC Registration §2), linked from the consent page; HTTPS, or plain HTTP on a loopback host.')
            ->defaultNull()
            ->end()
            ->scalarNode('tos_uri')
            ->info('The terms of service of this client (OIDC Registration §2), linked from the consent page; HTTPS, or plain HTTP on a loopback host.')
            ->defaultNull()
            ->end()
            ->arrayNode('contacts')
            ->info('Ways to reach the people responsible for this client (OIDC Registration §2), typically email addresses. No page shows them.')
            ->scalarPrototype()
            ->end()
            ->end()
            ->scalarNode('secret')
            ->info('At least 32 visible ASCII characters, generated, never chosen; absent for a public client.')
            ->defaultNull()
            ->end()
            ->arrayNode('redirect_uris')
            ->info('Compared byte for byte with the redirect_uri of a request (RFC 6749 §3.1.2.3); HTTPS, or plain HTTP on a loopback host.')
            ->scalarPrototype()
            ->end()
            ->end()
            ->arrayNode('post_logout_redirect_uris')
            ->info('Compared byte for byte with the post_logout_redirect_uri of a logout request (RP-Initiated Logout §3).')
            ->scalarPrototype()
            ->end()
            ->end()
            ->arrayNode('grant_types')
            ->info('What this client may ask for at the token endpoint (RFC 7591 §2), among the grants the provider is wired with; left out, it takes the browser flow and its renewal. A name nothing serves fails at boot.')
            ->defaultValue(DeploymentDefaults::GRANT_TYPES)
            ->scalarPrototype()
            ->end()
            ->end()
            ->arrayNode('response_types')
            ->info('What this client asks the authorization endpoint to answer with (OIDC Registration §2): "code" and nothing else, decision 0006 admitting no implicit flow. Left out, it is the one that goes with the grants above, and a pair that contradicts itself fails at boot.')
            ->scalarPrototype()
            ->end()
            ->end()
            ->scalarNode('scope')
            ->info('The closed list of scopes this client may ask for (RFC 7591 §2), space-delimited as a request writes it (RFC 6749 §3.3); a scope it did not register is refused with invalid_scope. Left out, it takes the three an application that signs a user in comes for.')
            ->defaultValue(DeploymentDefaults::SCOPE)
            ->end()
            ->scalarNode('token_endpoint_auth_method')
            ->info('How this client authenticates at the endpoints that authenticate a client (OIDC Core §9), among the methods the provider is wired with; left out, it takes the first wired one. A name nothing authenticates with fails at boot.')
            ->defaultNull()
            ->end()
            ->booleanNode('requires_consent')
            ->info('Consent is the rule; a first-party application is the named exception.')
            ->defaultTrue()
            ->end()
            ->booleanNode('requires_pkce')
            ->info('PKCE S256 is the rule; a confidential client that cannot send a code_challenge is the named exception of decision 0008, refused for a public client. A challenge the client sends is verified all the same.')
            ->defaultTrue()
            ->end()
            ->booleanNode('require_pushed_authorization_requests')
            ->info('The only way this client starts an authorization request is by pushing it (RFC 9126 §6), which is what FAPI 2.0 asks of one; an ordinary request from it is refused on a page before its redirect URI is even read. Per client, nothing global: the document announces the requirement when every registered client carries it.')
            ->defaultFalse()
            ->end()
            ->booleanNode('require_sender_constrained_tokens')
            ->info('The tokens of this client are bound to what the request proves it holds, or the request is refused (FAPI 2.0 Security Profile §5.3.1): a token request that proves neither a certificate (RFC 8705 §3) nor a key (RFC 9449 §5) is answered with an error rather than with bearer tokens. Per client, nothing global.')
            ->defaultFalse()
            ->end()
            ->booleanNode('tls_client_certificate_bound_access_tokens')
            ->info('The tokens of this client are bound to the certificate it presents at the TLS handshake, whichever way it authenticated (RFC 8705 §3.4), which is what FAPI 1.0 Advanced Final §5.2.2 asks of a client authenticating with an assertion on a profile that binds. A token request of this client that proves no certificate is refused rather than answered with tokens bound to nothing, before anything is read of what it came to spend. A client recognised by its certificate gets bound tokens anyway (§3); per client, nothing global.')
            ->defaultFalse()
            ->end()
            ->booleanNode('require_signed_request_object')
            ->info('A request of this client is only read from a request object it signed (RFC 9101 §10.5, require_signed_request_object; FAPI 2.0 Message Signing §5.3.1; FAPI-CIBA §5.2.2), whether the object arrives in the query, behind a request_uri, inside the record it pushed or in the body of a backchannel authentication request. An unsigned authorization request is refused on a page before its redirect URI is read, exactly as a request that was not pushed is; an unsigned backchannel one is refused invalid_request.')
            ->defaultFalse()
            ->end()
            ->scalarNode('id_token_signed_response_alg')
            ->info('The JWS algorithm the ID tokens and the logout tokens of this client are signed with (OIDC Registration §2), among those the provider is wired with; left out, the provider signs them with its default. A name nothing signs under fails at boot.')
            ->defaultNull()
            ->end()
            ->scalarNode('id_token_encrypted_response_alg')
            ->info('The JWE key management algorithm the ID tokens of this client are encrypted to one of its keys with, once signed (OIDC Core §3.1.3.7), among those the provider is wired with. It comes with id_token_encrypted_response_enc, never alone, and the client publishes a key it can be addressed to; left out, the ID token travels signed and in clear, which is what every client does today.')
            ->defaultNull()
            ->end()
            ->scalarNode('id_token_encrypted_response_enc')
            ->info('The JWE content encryption algorithm the payload of that ID token is encrypted with (OIDC Core §3.1.3.7), among those the provider is wired with. OIDC Registration §2 defaults it to a value this provider is not wired with, so it is named or it is refused at boot.')
            ->defaultNull()
            ->end()
            ->scalarNode('userinfo_signed_response_alg')
            ->info('The JWS algorithm the UserInfo answer of this client is signed with (OIDC Core §5.3.2), among those the provider is wired with; the answer is then served as "application/jwt" and carries an "iss" and an "aud" beside the claims. Left out, the answer is the plain JSON, which is what every client that asks for nothing receives.')
            ->defaultNull()
            ->end()
            ->scalarNode('userinfo_encrypted_response_alg')
            ->info('The JWE key management algorithm the UserInfo answer of this client is encrypted to one of its keys with (OIDC Core §5.3.2), among those the provider is wired with. It comes with userinfo_encrypted_response_enc, never alone. Without userinfo_signed_response_alg, what is encrypted is the plain JSON of the claims, §5.3.2 allowing an answer to be encrypted without being signed.')
            ->defaultNull()
            ->end()
            ->scalarNode('userinfo_encrypted_response_enc')
            ->info('The JWE content encryption algorithm the payload of that UserInfo answer is encrypted with (OIDC Core §5.3.2), among those the provider is wired with.')
            ->defaultNull()
            ->end()
            ->scalarNode('authorization_signed_response_alg')
            ->info('The JWS algorithm the signed authorization responses of this client are signed with (JARM §3), among those the provider is wired with; left out, the provider signs them with its default. It applies to the answers this client asks for with response_mode=jwt, query.jwt or form_post.jwt, a refusal as well as a code.')
            ->defaultNull()
            ->end()
            ->scalarNode('authorization_encrypted_response_alg')
            ->info('The JWE key management algorithm the signed authorization responses of this client are encrypted to one of its keys with, once signed (JARM §3), among those the provider is wired with. It comes with authorization_encrypted_response_enc, never alone.')
            ->defaultNull()
            ->end()
            ->scalarNode('authorization_encrypted_response_enc')
            ->info('The JWE content encryption algorithm the payload of that authorization response is encrypted with (JARM §3), among those the provider is wired with.')
            ->defaultNull()
            ->end()
            ->scalarNode('access_token_format')
            ->info('The shape the access tokens of this client are written in, among those the provider is wired to write: "jwt" (RFC 9068, verified offline against the JWK Set) or "opaque" (a reference the resource server introspects, RFC 7662, revocable at once). Left out, it takes the first wired one. A name nothing writes fails at boot. Per client, nothing global.')
            ->defaultNull()
            ->end()
            ->scalarNode('backchannel_logout_uri')
            ->info('Where the provider posts a logout token when a session this client signed in ends (Back-Channel Logout 1.0 §2.2); HTTPS, or plain HTTP on a loopback host. Absent for a client the provider does not tell.')
            ->defaultNull()
            ->end()
            ->booleanNode('backchannel_logout_session_required')
            ->info('The client reads the "sid" of the logout token to know which session ended (Back-Channel Logout 1.0 §2.2); it needs a backchannel_logout_uri. The provider sends "sid" either way.')
            ->defaultFalse()
            ->end()
            ->scalarNode('frontchannel_logout_uri')
            ->info('Loaded in a frame of the logout page when a session this client signed in ends (Front-Channel Logout 1.0 §3); HTTPS, or plain HTTP on a loopback host. Absent for a client the page does not load. It reaches the client only if the browser sends that client its cookies.')
            ->defaultNull()
            ->end()
            ->booleanNode('frontchannel_logout_session_required')
            ->info('The client reads "iss" and "sid" on its logout URI to know which session ended (Front-Channel Logout 1.0 §2); it needs a frontchannel_logout_uri. The two parameters are added for this client only, §2 making them conditional.')
            ->defaultFalse()
            ->end()
            ->variableNode('jwks')
            ->info('The JWK Set of the client, inline (RFC 7591 §2): public keys only, and exclusive with jwks_uri. A client that authenticates with private_key_jwt publishes one of the two.')
            ->defaultNull()
            ->end()
            ->scalarNode('jwks_uri')
            ->info('Where the JWK Set of the client is read back from (RFC 7591 §2); HTTPS, or plain HTTP on a loopback host, no redirect followed. Exclusive with jwks.')
            ->defaultNull()
            ->end()
            ->scalarNode('subject_type')
            ->info('The kind of "sub" this client sees for a user (OIDC Core §8), under the name the resolver of that kind gives itself, among the kinds this provider assigns one for, which is what subject_types_supported announces. Left out, the client registers none and sees the kind the provider assigns by default.')
            ->defaultNull()
            ->end()
            ->scalarNode('sector_identifier_uri')
            ->info('The document naming every redirection URI of the clients that share a "sub" with this one (OIDC Core §8.1); HTTPS, no redirect followed.')
            ->defaultNull()
            ->end()
            ->scalarNode('initiate_login_uri')
            ->info('Where a third party sends a user to have this provider begin a login at this client (OIDC Core §4, OIDC Registration §2); HTTPS, on a loopback host as anywhere else: §2 gives this member none of the tolerance the other URIs of a client keep.')
            ->defaultNull()
            ->end()
            ->scalarNode('request_object_signing_alg')
            ->info('The JWS algorithm the request objects of this client are signed with (OIDC Registration §2), among those the provider is wired with; left out, any of them verifies one. The value "none" is the named exception of decision 0006: the objects of that client carry no signature and are read all the same, which no FAPI client registers and a client with require_signed_request_object cannot (RFC 9101 §10.5). A client that names an algorithm publishes its keys in jwks or behind a jwks_uri.')
            ->defaultNull()
            ->end()
            ->scalarNode('backchannel_token_delivery_mode')
            ->info('How this client is told that a backchannel authentication request has been answered (CIBA Core §4), among the modes the provider is wired with: "poll" for a client that asks the token endpoint again until it is answered, "ping" for one this provider calls back first. There is no default: a client that registers none is not a client of that flow, and the endpoint where it starts refuses it. A name nothing serves fails at boot.')
            ->defaultNull()
            ->end()
            ->scalarNode('backchannel_client_notification_endpoint')
            ->info('Where this provider posts the identifier of a backchannel request once it has been answered (CIBA Core §7.1, §10.2); HTTPS, or plain HTTP on a loopback host, no redirect followed. It goes with a delivery mode where the provider calls the client, never alone, and never without one.')
            ->defaultNull()
            ->end()
            ->arrayNode('resources')
            ->info('The resources this client may ask an access token for (RFC 8707 §2 "resource"), each an absolute URI without a fragment; a resource it did not register is refused with invalid_target. A closed list, no wildcard: a client that registers none asks for none, and its tokens are addressed to itself.')
            ->scalarPrototype()
            ->end()
            ->end()
            ->arrayNode('authorization_details_types')
            ->info('The types of authorization detail this client may ask for (RFC 9396 §2 "authorization_details"), among the ones the provider is wired with; a type it did not register, and a type nothing serves, are both refused with invalid_authorization_details. A closed list, no wildcard: a client that registers none asks for none. A type is a class the deployment tags, which validates its own members and says what a page shows of them: the bundle wires none, no type of detail being universal.')
            ->scalarPrototype()
            ->end()
            ->end()
            ->arrayNode('token_exchange')
            ->info('What this client may do at the token exchange (RFC 8693 §2.1), for a client registered for that grant and for no other. A closed declaration: a client presenting something it did not register for is refused whatever the thing says. Which resources the new token may be addressed to is the resources option above, as it is for every other grant.')
            ->children()
            ->arrayNode('subject_token_types')
            ->info('The types of token this client may present as a subject_token or as an actor_token (RFC 8693 §3), among those the provider is wired to read; at least one. A name nothing reads fails at boot.')
            ->scalarPrototype()
            ->end()
            ->end()
            ->booleanNode('may_act_for_a_user')
            ->info('Whether this client may present a token somebody signed in for. False for a service that only ever exchanges tokens of its own (RFC 6749 §4.4): a gateway carrying a user\'s token is not the same party, and a deployment says which of the two it registered.')
            ->defaultFalse()
            ->end()
            ->end()
            ->end()
            ->scalarNode('may_act')
            ->info('Who may act for the subject of a token issued to this client (RFC 8693 §4.4), as a subject: it is written on every token this client receives, and an exchange asked for by anybody else is refused. Absent, the token says nothing and what decides is the registration of whoever asks.')
            ->defaultNull()
            ->end()
            ->arrayNode('request_uris')
            ->info('The URLs a request object of this client is read back from (OIDC Registration §2), compared byte for byte with the request_uri of a request; one that is not registered is refused before any request leaves the process, which is what require_request_uri_registration announces.')
            ->scalarPrototype()
            ->end()
            ->end()
            ->scalarNode(CertificateIdentities::SUBJECT_DN)
            ->info('The subject distinguished name of the certificate this client presents (RFC 8705 §2.1.2), in the string form of RFC 4514; it is written back at boot the way the provider writes the name it reads out of a certificate, so a name as "openssl x509 -noout -subject -nameopt RFC2253" prints it is registered as it is. One of the five keys below, and one only, for a client that authenticates with tls_client_auth.')
            ->defaultNull()
            ->end()
            ->scalarNode(CertificateIdentities::SAN_DNS)
            ->info('The dNSName entry of the subject alternative name extension this client is recognised by (RFC 8705 §2.1.2), compared without regard to case (RFC 4343 §1).')
            ->defaultNull()
            ->end()
            ->scalarNode(CertificateIdentities::SAN_URI)
            ->info('The uniformResourceIdentifier entry this client is recognised by (RFC 8705 §2.1.2), compared as the text it is.')
            ->defaultNull()
            ->end()
            ->scalarNode(CertificateIdentities::SAN_IP)
            ->info('The iPAddress entry this client is recognised by (RFC 8705 §2.1.2), in dotted decimal or colon-delimited hexadecimal; it is compared as the octets it stands for, not as the text.')
            ->defaultNull()
            ->end()
            ->scalarNode(CertificateIdentities::SAN_EMAIL)
            ->info('The rfc822Name entry this client is recognised by (RFC 8705 §2.1.2), compared as it is written (RFC 5321 §2.4).')
            ->defaultNull()
            ->end()
            ->end()
            ->end()
            ->end();
    }

    public function load(array $config, ServicesConfigurator $services, bool $debug): void
    {
        $services->get(ConfigurationClientRepository::class)->arg('$tenantSlug', self::string(self::section($config, 'tenant'), 'slug'))->arg(
            '$definitions',
            is_array($config['clients'] ?? null) ? $config['clients'] : [],
        );
    }
}
